-- 3. estimate_eu
CREATE TABLE estimate_eu (
  id SERIAL PRIMARY KEY,
  user_id UUID REFERENCES profiles(id),
  project_id INTEGER REFERENCES project(id),
  estimate_reu_id INTEGER REFERENCES estimate_reu(id),
  order_uid VARCHAR(255),
  reference VARCHAR(255),
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW(),
  company_id INTEGER REFERENCES company(id)
);

-- 4. eu_reports
CREATE TABLE eu_reports (
  id SERIAL PRIMARY KEY,
  user_id UUID REFERENCES profiles(id),
  estimate_eu_id INTEGER UNIQUE REFERENCES estimate_eu(id),
  report_id INTEGER REFERENCES report(id),
  project_id INTEGER REFERENCES project(id),
  status VARCHAR(255) NOT NULL,
  bidding BOOLEAN NOT NULL
);

-- 5. electrician_bids
CREATE TABLE electrician_bids (
  id SERIAL PRIMARY KEY,
  project_id INTEGER REFERENCES project(id),
  estimate_eu_id INTEGER REFERENCES estimate_eu(id),
  report_id INTEGER REFERENCES report(id),
  user_id UUID REFERENCES profiles(id),
  labor VARCHAR(255) NOT NULL,
  materials VARCHAR(255) NOT NULL,
  permits VARCHAR(255) NOT NULL,
  tax VARCHAR(255) NOT NULL,
  disposal VARCHAR(255) NOT NULL,
  availability TEXT NOT NULL,
  total VARCHAR(255) NOT NULL,
  bid_status VARCHAR(255) NOT NULL,
  company_name VARCHAR(255) NOT NULL,
  seen BOOLEAN NOT NULL
);

-- 6. shipping_detail
CREATE TABLE shipping_detail (
  id SERIAL PRIMARY KEY,
  estimate_su_id INTEGER REFERENCES estimate(id),
  sender_company_name VARCHAR(255),
  sender_tracking_link VARCHAR(255),
  sender_country VARCHAR(255),
  sender_address1 VARCHAR(255),
  sender_address2 VARCHAR(255),
  sender_city VARCHAR(255),
  sender_state VARCHAR(255),
  sender_zip_code VARCHAR(255),
  sender_phone VARCHAR(255),
  receiver_company_name VARCHAR(255),
  receiver_name VARCHAR(255),
  receiver_country VARCHAR(255),
  receiver_address1 VARCHAR(255),
  receiver_address2 VARCHAR(255),
  receiver_city VARCHAR(255),
  receiver_state VARCHAR(255),
  receiver_zip_code VARCHAR(255),
  receiver_phone VARCHAR(255),
  status INTEGER NOT NULL,
  shipping_reference VARCHAR(255) NOT NULL,
  luminaires JSONB,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW(),
  notes VARCHAR(255)
);
