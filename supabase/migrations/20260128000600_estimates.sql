  fulfilled_by_user_invoice_reu_id UUID REFERENCES profiles(id),
  archived_by_user_estimate_reu_id UUID REFERENCES profiles(id),
  fulfilled_by_user_receipt_reu_id UUID REFERENCES profiles(id),
  user_reu_id UUID REFERENCES profiles(id),
  company_id INTEGER REFERENCES company(id),
  report_id INTEGER REFERENCES report(id),
  user_admin_consultant_id UUID REFERENCES profiles(id),
  order_uid VARCHAR(255),
  reference VARCHAR(255),
  reu_signature TEXT,
  reu_signature_date VARCHAR(255),
  admin_signature_date VARCHAR(255),
  admin_signature TEXT,
  sales_tax VARCHAR(255),
  rebates VARCHAR(255),
  shipping VARCHAR(255),
  reu_approved BOOLEAN,
  reu_notes VARCHAR(255),
  deposit_amount VARCHAR(255),
  deposit_due TEXT,
  remainder_due TEXT,
  remainder_amount VARCHAR(255),
  is_order BOOLEAN,
  is_estimate BOOLEAN,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW(),
  order_date_created TIMESTAMPTZ DEFAULT NOW(),
  order_date_updated TIMESTAMPTZ DEFAULT NOW(),
  is_shipping BOOLEAN,
  shipping_status VARCHAR(255),
  shipping_date_created TIMESTAMPTZ DEFAULT NOW(),
  shipping_date_updated TIMESTAMPTZ DEFAULT NOW(),
  is_invoice BOOLEAN,
  invoice_date_created TIMESTAMPTZ DEFAULT NOW(),
  invoice_date_updated TIMESTAMPTZ DEFAULT NOW(),
  is_receipt BOOLEAN,
  receipt_date_created TIMESTAMPTZ DEFAULT NOW(),
  receipt_date_updated TIMESTAMPTZ DEFAULT NOW(),
  deposit_paid_date TEXT,
  remainder_due_date TEXT,
  marked_fulfilled BOOLEAN,
  archived BOOLEAN,
  archived_date_created TIMESTAMPTZ DEFAULT NOW(),
  archived_date_updated TIMESTAMPTZ DEFAULT NOW(),
  marked_fulfilled_date_created TIMESTAMPTZ DEFAULT NOW(),
  marked_fulfilled_date_updated TIMESTAMPTZ DEFAULT NOW(),
  luminaires JSONB
);

